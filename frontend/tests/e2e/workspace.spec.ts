test("research variants can be run, compared, archived, and exported",async ({page})=>{
  await page.goto("/?view=research");
  await page.getByLabel("Experiment name").fill("Evening network comparison");
  await page.getByLabel("Research notes").fill("Hold the seed fixed and compare interventions.");
  await page.getByRole("button",{name:"Create experiment",exact:true}).click();
  await page.getByRole("button",{name:"Add scenario variant",exact:true}).click();
  const form=page.getByRole("dialog");
  await form.getByLabel("Title",{exact:true}).fill("Fixed seed variant");
  await form.getByLabel("Simulation seed").fill("94");
  await form.getByLabel("Use the scenario’s default specialists").uncheck();
  await form.getByRole("button",{name:"Run simulation",exact:true}).click();
  const table=page.getByRole("table",{name:"Experiment outcomes at +30 minutes"});
  await expect(table.getByRole("cell",{name:"Completed"})).toBeVisible({timeout:15000});
  await expect(table.getByRole("cell",{name:"94",exact:true}).first()).toBeVisible();
  const link=await page.getByRole("link",{name:"Export experiment"}).getAttribute("href");
  expect(link).toBeTruthy();
  const download=await page.request.get(link!);
  expect((await download.json()).variants[0].seed).toBe(94);
  await page.getByRole("button",{name:"Archive experiment",exact:true}).click();
  await expect(page.getByRole("button",{name:"Restore experiment",exact:true})).toBeVisible();
  await expect(page.getByRole("button",{name:"Add scenario variant",exact:true})).toHaveCount(0);
});

test("GTFS ZIP data is visible in Mobility and access credentials are revocable",async ({page})=>{
  await page.goto("/account?mode=register");
  await page.getByLabel("Name",{exact:true}).fill("Integration Tester");
  await page.getByLabel("Email address").fill("integrations-"+crypto.randomUUID()+"@example.test");
  await page.getByLabel("Password",{exact:true}).fill("example-integrations-test");
  await page.getByRole("button",{name:"Create account",exact:true}).click();
  await page.getByRole("button",{name:"Settings",exact:true}).click();
  await page.getByRole("button",{name:"Data sources",exact:true}).click();
  const data=page.locator("section").filter({has:page.getByRole("heading",{name:"Data sources",exact:true})});
  await data.getByLabel("Name",{exact:true}).fill("Schedule demo");
  await data.getByLabel("Format").selectOption("gtfs-zip");
  await data.getByLabel("File").setInputFiles(resolve(process.cwd(),"../examples/debrecen-transit.zip"));
  await data.getByRole("button",{name:"Import",exact:true}).click();
  await expect(data.getByText("Schedule demo",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Mobility",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Demo T7",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Settings",exact:true}).click();
  await page.getByRole("button",{name:"API credentials",exact:true}).click();
  await page.getByLabel("Credential name").fill("Local integration test");
  await page.getByLabel("Read city data").check();
  await page.getByRole("button",{name:"Create API credential",exact:true}).click();
  const input=page.getByLabel("Copy this credential now. It is shown once.");
  await expect(input).toHaveValue(/^act_/);
  const headers={Authorization:`Bearer ${await input.inputValue()}`};
  expect((await page.request.get("/api/v1/mobility",{headers})).ok()).toBe(true);
  await page.getByRole("button",{name:"Revoke",exact:true}).click();
  await page.getByRole("button",{name:"Confirm revocation",exact:true}).click();
  await expect(page.getByText("Credential revoked.")).toBeVisible();
  expect((await page.request.get("/api/v1/mobility",{headers})).status()).toBe(401);
});
