test("Debrecen incident to verified recommendation, map, audit, and export", async ({page})=>{
  const styleErrors:string[]=[];
  page.on("console",message=>{
    if(message.type()==="error"&&/layers\..*(modeled-emissions|map-points|flow-glow|flow\.)/.test(message.text()))styleErrors.push(message.text());
  });
  await page.goto("/");
  await expect(page.getByRole("heading",{name:"Debrecen Digital Twin",exact:true})).toBeVisible();
  await expect(page.locator(".maplibregl-canvas")).toBeVisible();
  await page.getByRole("button",{name:"Layers",exact:true}).click();
  const transit=page.getByRole("checkbox",{name:"Transit",exact:true});
  await transit.check();
  await expect(transit).toBeChecked();
  await page.getByRole("button",{name:"Layers",exact:true}).click();
  await page.getByRole("button",{name:"University corridor accident"}).click();
  await page.getByRole("button",{name:"Analyze scenario"}).click();
  await expect(page.getByRole("heading",{name:"Diversion and transit priority"})).toBeVisible({timeout:35_000});
  await page.getByRole("button",{name:"Predicted",exact:true}).click();
  await page.getByRole("button",{name:"+60 min",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Outcome comparison · +60m"})).toBeVisible();
  const forecast=page.getByLabel("Modeled map conditions");
  await expect(forecast.getByText("Incident phase Active")).toBeVisible();
  const start=await forecast.getByText("Modeled emissions change", {exact:false}).innerText();
  const delay=await forecast.getByText("Modeled transit delay", {exact:false}).innerText();
  await page.getByRole("button",{name:"+2h",exact:true}).click();
  await expect(forecast.getByText("Incident phase Recovery")).toBeVisible();
  await expect(forecast.getByText("Modeled emissions change",{exact:false})).not.toHaveText(start);
  await expect(forecast.getByText("Modeled transit delay",{exact:false})).not.toHaveText(delay);
  expect(styleErrors).toEqual([]);
  await page.getByRole("button",{name:"Why did AgentCity choose this?"}).click();
  await expect(page.locator("summary").filter({hasText:"Agent consensus and disagreements"})).toBeVisible();
  await expect(page.getByText("Negotiated revision",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Audit trace",exact:true}).click();
  await expect(page.getByRole("region",{name:"Simulation results"}).getByText("Timeline coverage and score bounds passed verification.",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Execution plan",exact:true}).click();
  const plan=page.getByRole("region",{name:"Execution plan",exact:true});
  await expect(plan.getByText("Awaiting operator review",{exact:true})).toBeVisible();
  await expect(plan.getByText("Test the negotiated revision.",{exact:true})).toBeVisible();
  await expect(plan.getByText("Success criteria",{exact:true})).toBeVisible();
  await plan.getByText("Test the negotiated revision.",{exact:true}).click();
  await expect(plan.getByText("The network model returned candidates.",{exact:true}).last()).toBeVisible();
  const href=await page.getByRole("link",{name:"Export JSON"}).getAttribute("href");
  expect(href).not.toBeNull();
  const response=await page.request.get(href!);
  expect(response.ok()).toBe(true);
  expect((await response.json()).result.verified).toBe(true);
  await page.getByRole("button",{name:"Notifications",exact:true}).click();
  await expect(page.getByRole("dialog",{name:"Notifications"}).getByText(/Agent completed|Agent model failed/).first()).toBeVisible();
});

